/** 判断某技能是否属于高威胁大招（触发 Boss 放狠话） */
export function isHighThreatBossSkill(
  skill: BossSkill,
  rule?: Pick<BossSkillDbmRule, 'severity'> | null
): boolean {
  const sev = skill.dbm?.severity || rule?.severity;
  if (sev === 'CRITICAL' || sev === 'WARN') return true;
  if (skill.interruptible) return true;
  if (skill.castTimeMs >= 1500) return true;
  if (skill.cooldownMs >= 18_000) return true;
  if (skill.targetKind === 'AOE') return true;
  return false;
}

/**
 * 为单个 Boss 维护不重复随机狠话洗牌袋（Shuffle Bag）。
 */
export class BossTrashTalkDeck {
  private readonly lines: string[];
  private bag: number[] = [];
  private lastIdx = -1;

  constructor(bossId: string, customLines?: string[]) {
    const base =
      (customLines && customLines.length > 0 ? customLines : undefined) ||
      BOSS_TRASH_TALK_LINES[bossId] ||
      BOSS_TRASH_TALK_LINES[bossId.replace(/_\d+$/, '')] ||
      DEFAULT_TRASH_TALK_LINES;
    this.lines = [...new Set(base.filter((s) => typeof s === 'string' && s.trim().length > 0))];
    if (this.lines.length === 0) {
      this.lines = [...DEFAULT_TRASH_TALK_LINES];
    }
    this.refillBag();
  }

  private refillBag(): void {
    const indices = this.lines.map((_, i) => i);
    for (let i = indices.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [indices[i], indices[j]] = [indices[j], indices[i]];
    }
    // 防止跨轮洗牌时首句与上一轮末句撞车
    if (indices.length > 1 && indices[indices.length - 1] === this.lastIdx) {
      [indices[0], indices[indices.length - 1]] = [indices[indices.length - 1], indices[0]];
    }
    this.bag = indices;
  }

  public nextLine(): string {
    if (this.bag.length === 0) {
      this.refillBag();
    }
    const idx = this.bag.pop()!;
    this.lastIdx = idx;
    return this.lines[idx];
  }

  public getPoolSize(): number {
    return this.lines.length;
  }
}
